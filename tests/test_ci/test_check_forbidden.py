"""Unit tests for scripts/ci/check_forbidden.py.

Every "secret" here is an obviously fake sample, assembled at run time so that this
file's own lines never match the scanner (it scans the lines a PR adds, including these).
"""

import base64
import json
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts" / "ci"))

import check_forbidden as cf  # noqa: E402
from ci_common import parse_unified_diff  # noqa: E402

DASHES = "-" * 5
FAKE_KEY_HEADER = DASHES + "BEGIN " + "FAKE TEST " + "PRIVATE KEY" + DASHES
FAKE_OPENSSH_HEADER = DASHES + "BEGIN OPENSSH " + "PRIVATE KEY" + DASHES


def b64(obj) -> str:
    return base64.urlsafe_b64encode(json.dumps(obj).encode()).decode().rstrip("=")


FAKE_JWT = ".".join([b64({"alg": "none", "fake": True}), b64({"sub": "nobody-fake"}), "not-a-signature"])
PW_NAME = "pass" + "word"
FAKE_VALUE = "zz" + "-not-real-" + "zz"
FAKE_SEEDED = ["ZZFAKE-0001", "99999", "1 Nowhere Lane, Fakeville"]


@pytest.mark.parametrize("path, rule", [
    (".env", ".env*"), (".env.local", ".env*"), ("deploy/.env.prod", ".env*"),
    ("keys/agent.txt", "keys/"), ("broker/keys/x.json", "keys/"),
    ("certs/server.pem", "*.pem"), ("CERT.PEM", "*.pem"), ("a/b.key", "*.key"),
    ("data/world.sqlite", "*.sqlite"), ("mock.db", "*.db"),
    ("logs/planner.jsonl", "logs/"), ("results/run1/results.csv", "results/"),
    ("scenarios/source/team.csv", "scenarios/source/"), ("notes/Explainer.docx", "*.docx"),
])
def test_forbidden_paths(path, rule):
    assert cf.forbidden_path_rule(path) == f"forbidden-file({rule})"


@pytest.mark.parametrize("path", [
    "broker/identity/keys.py", "docs/results.md", "agents/planner.py", "scenarios/a1.json",
    "tests/test_runner/test_results.py", "docs/keystore.md", "README.md", "environment.md",
])
def test_allowed_paths(path):
    assert cf.forbidden_path_rule(path) is None


def test_private_key_headers_are_found():
    assert cf.scan_line(FAKE_KEY_HEADER, None) == ["private-key-header"]
    assert cf.scan_line("x = '" + FAKE_OPENSSH_HEADER + "'", None) == ["private-key-header"]


def test_jwt_shaped_strings_are_found():
    assert "jwt-shaped-string" in cf.scan_line(f"Authorization: Bearer {FAKE_JWT}", None)
    assert cf.scan_line("eyJ is just a prefix", None) == []


@pytest.mark.parametrize("line", [
    f'{PW_NAME} = "{FAKE_VALUE}"',
    f"db_{PW_NAME}: '{FAKE_VALUE}'",
    f'"api_key": "{FAKE_VALUE}"',
    f'API-KEY="{FAKE_VALUE}"',
    f'client_secret = "{FAKE_VALUE}"',
    f'send(auth_token="{FAKE_VALUE}")',
])
def test_secret_assignments_are_found(line):
    assert cf.scan_line(line, None) == ["secret-assignment"]


@pytest.mark.parametrize("line", [
    f"{PW_NAME} = os.environ['DB_PASS']",      # not a literal
    f'{PW_NAME} = ""',                          # empty
    'token="stub-token-for-tests"',                 # placeholder word
    'step(token="expired")',                         # scripted attacker token mode
    'api_key: "${API_KEY}"',                         # template
    f'{PW_NAME}: "<your value here>"',
    "max_tokens = 256",
    "token_for(receiver)",
])
def test_non_secrets_are_not_flagged(line):
    assert cf.scan_line(line, None) == []


def test_seeded_values_match_whole_values_only():
    rx = cf.seeded_value_pattern(FAKE_SEEDED)
    assert cf.scan_line("leaked ZZFAKE-0001 here", rx) == ["seeded-sensitive-value"]
    assert cf.scan_line("salary 99999.", rx) == ["seeded-sensitive-value"]
    assert cf.scan_line("lives at 1 Nowhere Lane, Fakeville", rx) == ["seeded-sensitive-value"]
    assert cf.scan_line("id 1999990 and ZZFAKE-00012", rx) == []
    assert cf.seeded_value_pattern([]) is None


def test_seeded_values_come_from_the_seed_generator():
    """Values are generated by mocks/seed.py at run time, never hardcoded in the check."""
    from mocks.seed import sensitive_values
    expected = [str(v) for vs in sensitive_values().values() for v in vs]
    loaded = cf.load_seeded_values("HEAD")
    assert set(expected) <= set(loaded) and expected
    rx = cf.seeded_value_pattern(loaded)
    assert all(rx.search(f"x {v} y") for v in expected)
    source = (REPO_ROOT / "scripts" / "ci" / "check_forbidden.py").read_text(encoding="utf-8")
    assert not any(v in source for v in expected)


DIFF = "\n".join([
    "diff --git a/app.py b/app.py",
    "index 1111111..2222222 100644",
    "--- a/app.py",
    "+++ b/app.py",
    "@@ -3,0 +4,2 @@ def f():",
    f'+{PW_NAME} = "{FAKE_VALUE}"',
    "+++ a content line that starts with two plus signs",
    "@@ -10 +12 @@",
    "-old",
    "+" + FAKE_KEY_HEADER,
    "diff --git a/.env b/.env",
    "new file mode 100644",
    "--- /dev/null",
    "+++ b/.env",
    "@@ -0,0 +1 @@",
    "+HELLO=world",
])


def test_diff_parsing_line_numbers():
    files = parse_unified_diff(DIFF)
    assert set(files) == {"app.py", ".env"}
    assert [n for n, _ in files["app.py"].added] == [4, 5, 12]
    assert files["app.py"].added[1][1].startswith("++ a content line")
    assert files["app.py"].removed == [(10, "old")]


def test_check_reports_rule_and_location_but_never_the_text(capsys):
    findings = cf.check(["app.py", ".env"], parse_unified_diff(DIFF), cf.seeded_value_pattern(FAKE_SEEDED))
    assert findings == [
        "forbidden-file(.env*): .env",
        "secret-assignment: app.py:4",
        "private-key-header: app.py:12",
    ]
    assert not any(FAKE_VALUE in f or "BEGIN" in f for f in findings)
